def load_ssot_constitution_rows():
    """从 SSOT 读取体质条目，用于生成结果页的溯源清单。"""
    out = {}
    with open(SSOT, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            if r["主题"] != "体质":
                continue
            for c in CONSTITUTIONS:
                if c in r["适用体质"] and c not in out:
                    out[c] = {"id": r["ID"], "name": r["条目名"], "point": r["内容要点"]}
    return out


